// Command typegen regenerates ext/jsvm/types.d.ts (run it with `go generate` in ext/jsvm):
//
//  1. PocketBase's own generator (plugins/jsvm/internal/types), copied unchanged to a temp folder and run against this
//     repo's core, so the declarations match PocketOne's core (its hooks included) rather than upstream's.
//  2. ext/jsvm/pocketone.d.ts: what this engine adds (.async, require, Buffer, process, import.meta, ...).
//
// Extensions add their own declarations when the app starts (js.Typer); they aren't part of this file.
package main

import (
	"context"
	"fmt"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"time"
)

const header = "// GENERATED by `go generate` in ext/jsvm (internal/typegen): PocketBase's declarations for PocketOne's core,\n" +
	"// then ext/jsvm/pocketone.d.ts. Don't edit; change the Go code or pocketone.d.ts and regenerate.\n"

func main() {
	jsvmDir, err := os.Getwd()
	if err != nil {
		log.Fatal(err)
	}
	root := filepath.Join(jsvmDir, "..", "..")
	upstream := filepath.Join(root, "plugins", "jsvm", "internal", "types", "types.go")

	tmp, err := os.MkdirTemp("", "jsvm-typegen-")
	if err != nil {
		log.Fatal(err)
	}
	defer os.RemoveAll(tmp)
	src, err := os.ReadFile(upstream)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(tmp, "types.go"), src, 0o644); err != nil {
		log.Fatal(err)
	}
	if err := os.Mkdir(filepath.Join(tmp, "generated"), 0o755); err != nil {
		log.Fatal(err)
	}

	// run in the root module, so it reads this repo's core
	fmt.Printf("%s typegen: running PocketBase's generator against %s\n", time.Now().Format("15:04:05"), root)
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
	defer cancel()
	cmd := exec.CommandContext(ctx, "go", "run", filepath.Join(tmp, "types.go"))
	cmd.Dir = root
	cmd.Stdout, cmd.Stderr = os.Stdout, os.Stderr
	if err := cmd.Run(); err != nil {
		log.Fatalf("typegen: PocketBase's generator: %v", err)
	}

	base, err := os.ReadFile(filepath.Join(tmp, "generated", "types.d.ts"))
	if err != nil {
		log.Fatal(err)
	}
	// drop the generator's timestamp line, so the file only changes when the declarations do
	body := string(base)
	if strings.HasPrefix(body, "// ") {
		if i := strings.IndexByte(body, '\n'); i >= 0 {
			body = body[i+1:]
		}
	}
	body = strings.Replace(body, "// GENERATED CODE - DO NOT MODIFY BY HAND\n", "", 1)
	body = normalize(body)

	extra, err := os.ReadFile(filepath.Join(jsvmDir, "pocketone.d.ts"))
	if err != nil {
		log.Fatal(err)
	}
	out := header + body + "\n" + string(extra)
	if err := os.WriteFile(filepath.Join(jsvmDir, "types.d.ts"), []byte(out), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("%s typegen: wrote types.d.ts (%d KB)\n", time.Now().Format("15:04:05"), len(out)/1024)
}

// tygoja names its helper types randomly (type _sAgVesS = ...) and emits packages in Go's random map order, so two runs
// differ. normalize sorts the top-level namespace blocks and renames each helper type in order of first use, so the
// file only changes when the declarations do (and a CI check can compare it).
func normalize(body string) string {
	lines := strings.SplitAfter(body, "\n")
	var prefix, suffix strings.Builder
	var blocks []string
	var cur *strings.Builder
	seenBlock := false
	for _, l := range lines {
		switch {
		case cur == nil && strings.HasPrefix(l, "namespace "):
			cur = &strings.Builder{}
			cur.WriteString("declare " + l)
			seenBlock = true
		case cur != nil:
			cur.WriteString(l)
			if l == "}\n" || l == "}" {
				blocks = append(blocks, cur.String())
				cur = nil
			}
		case !seenBlock:
			prefix.WriteString(l)
		default:
			suffix.WriteString(l)
		}
	}
	if cur != nil {
		blocks = append(blocks, cur.String())
	}

	// after the blocks come the packages' doc comments, also in random order
	comments := regexp.MustCompile(`(?s)/\*\*.*?\*/`).FindAllString(suffix.String(), -1)
	rest := strings.TrimSpace(regexp.MustCompile(`(?s)/\*\*.*?\*/`).ReplaceAllString(suffix.String(), ""))
	sort.Strings(comments)
	tail := "\n" + strings.Join(comments, "\n\n") + "\n"
	if rest != "" {
		tail += "\n" + rest + "\n"
	}

	defRe := regexp.MustCompile(`\btype (_s[A-Za-z0-9]+)(<[^>]*>)? =`)
	helpers := map[string]bool{}
	for _, m := range defRe.FindAllStringSubmatch(body, -1) {
		helpers[m[1]] = true
	}
	useRe := regexp.MustCompile(`\b_s[A-Za-z0-9]+\b`)
	mask := func(s string) string {
		return useRe.ReplaceAllStringFunc(s, func(n string) string {
			if helpers[n] {
				return "_s"
			}
			return n
		})
	}
	sort.SliceStable(blocks, func(i, j int) bool { return mask(blocks[i]) < mask(blocks[j]) })

	out := prefix.String() + strings.Join(blocks, "") + tail
	names := map[string]string{}
	return useRe.ReplaceAllStringFunc(out, func(n string) string {
		if !helpers[n] {
			return n
		}
		if _, ok := names[n]; !ok {
			names[n] = fmt.Sprintf("_t%03d", len(names)+1)
		}
		return names[n]
	})
}
