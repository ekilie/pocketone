package main

// The field types table on the Collections and fields page, read from core's field structs (core/field_*.go) so it
// follows upstream: each field type's name, what it stores (its doc comment's first sentence) and its options (the
// struct's JSON keys, past the ones every field has). site/sync writes it between two markers in the hand-written
// page, so the prose around it stays hand-written.

import (
	"fmt"
	"go/ast"
	"go/doc"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"reflect"
	"regexp"
	"strconv"
	"strings"
)

const (
	fieldsPage  = "site/pb_pages/(main)/docs/collections.md"
	fieldsStart = "<!-- field-types:start (generated by site/sync from core/field_*.go) -->"
	fieldsEnd   = "<!-- field-types:end -->"
)

// fieldsCommon are the keys every field has; the table lists the rest.
var fieldsCommon = map[string]bool{"id": true, "name": true, "system": true, "hidden": true, "presentable": true}

type fieldType struct {
	Go, Type, Stores string
	Options          []string
}

// fieldTypes reads core's field types, in the order the dashboard offers them.
func fieldTypes(root string) ([]fieldType, error) {
	fset := token.NewFileSet()
	dir := filepath.Join(root, "core")
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var files []*ast.File
	for _, e := range entries {
		n := e.Name()
		if !strings.HasPrefix(n, "field_") || !strings.HasSuffix(n, ".go") || strings.HasSuffix(n, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, n), nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		files = append(files, f)
	}
	pkg, err := doc.NewFromFiles(fset, files, "core", doc.AllDecls)
	if err != nil {
		return nil, err
	}
	consts := map[string]string{} // FieldTypeText -> "text"
	collect := func(vs []*doc.Value) {
		for _, v := range vs {
			for _, spec := range v.Decl.Specs {
				vsp, ok := spec.(*ast.ValueSpec)
				if !ok {
					continue
				}
				for i, n := range vsp.Names {
					if i < len(vsp.Values) {
						if lit, ok := vsp.Values[i].(*ast.BasicLit); ok && lit.Kind == token.STRING {
							consts[n.Name], _ = strconv.Unquote(lit.Value)
						}
					}
				}
			}
		}
	}
	collect(pkg.Consts)
	for _, t := range pkg.Types {
		collect(t.Consts)
	}
	var out []fieldType
	for _, t := range pkg.Types {
		if !strings.HasSuffix(t.Name, "Field") || t.Name == "Field" || !ast.IsExported(t.Name) {
			continue
		}
		typ := consts["FieldType"+strings.TrimSuffix(t.Name, "Field")]
		if typ == "" {
			continue
		}
		ts, ok := t.Decl.Specs[0].(*ast.TypeSpec)
		if !ok {
			continue
		}
		st, ok := ts.Type.(*ast.StructType)
		if !ok {
			continue
		}
		// "aka." would end the first sentence early
		ft := fieldType{Go: t.Name, Type: typ, Stores: fieldStores(pkg.Synopsis(strings.ReplaceAll(t.Doc, "aka.", "aka")))}
		for _, f := range st.Fields.List {
			if f.Tag == nil || len(f.Names) == 0 || !ast.IsExported(f.Names[0].Name) {
				continue
			}
			tag, _ := strconv.Unquote(f.Tag.Value)
			key := strings.Split(reflect.StructTag(tag).Get("json"), ",")[0]
			if key == "" || key == "-" || fieldsCommon[key] {
				continue
			}
			ft.Options = append(ft.Options, key)
		}
		out = append(out, ft)
	}
	order := map[string]int{"text": 1, "editor": 2, "number": 3, "bool": 4, "email": 5, "url": 6, "date": 7, "autodate": 8,
		"select": 9, "file": 10, "relation": 11, "json": 12, "geoPoint": 13, "password": 14}
	sortBy(out, func(a, b fieldType) bool {
		oa, ob := order[a.Type], order[b.Type]
		if oa == 0 {
			oa = 99
		}
		if ob == 0 {
			ob = 99
		}
		return oa < ob || oa == ob && a.Type < b.Type
	})
	return out, nil
}

var fieldDefinesRe = regexp.MustCompile(`^\w+ defines (an? )?"[^"]+" type field,? (aka field which |for |to )?(storing |store |managing )?`)

// fieldStores turns "TextField defines "text" type field for storing any string value." into "Any string value."
// (and "... to store ...", "an "autodate" type field, aka field which ...").
func fieldStores(s string) string {
	s = strings.TrimSpace(fieldDefinesRe.ReplaceAllString(s, ""))
	if s == "" {
		return ""
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

func sortBy[T any](xs []T, less func(a, b T) bool) {
	for i := 1; i < len(xs); i++ {
		for j := i; j > 0 && less(xs[j], xs[j-1]); j-- {
			xs[j], xs[j-1] = xs[j-1], xs[j]
		}
	}
}

// fieldsTable is the generated block.
func fieldsTable(fts []fieldType) string {
	var b strings.Builder
	b.WriteString(fieldsStart + "\n\n| Type | Stores | Options | Reference |\n|---|---|---|---|\n")
	for _, f := range fts {
		opts := make([]string, len(f.Options))
		for i, o := range f.Options {
			opts[i] = "`" + o + "`"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | [JS](/docs/reference/javascript/pocketbase/core/fields#%s) · [Go](/docs/reference/go/pocketbase/core/fields#%s) |\n",
			f.Type, cell(f.Stores), strings.Join(opts, ", "), gid("core."+f.Go), gid(f.Go))
	}
	b.WriteString("\n" + fieldsEnd)
	return b.String()
}

// fieldsInPage puts the table between the markers of the Collections page; a page without them is left alone.
func fieldsInPage(root string, out map[string]string) error {
	raw, err := os.ReadFile(filepath.Join(root, fieldsPage))
	if err != nil {
		return nil
	}
	page := string(raw)
	i, j := strings.Index(page, fieldsStart), strings.Index(page, fieldsEnd)
	if i < 0 || j < i {
		return nil
	}
	fts, err := fieldTypes(root)
	if err != nil {
		return err
	}
	out[fieldsPage] = page[:i] + fieldsTable(fts) + page[j+len(fieldsEnd):]
	return nil
}
