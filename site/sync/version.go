package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
)

// versionOut holds PocketOne's current release for the version pill in the site header (+layout.ejs loads it with
// ctx.resolve, so a deploy shows a new release without a restart).
const versionOut = "site/pb_pages/_private/version.js"

// releaseHeading is a release's section in the root CHANGELOG.md: "## v0.0.1-alpha.6 (2026-11-16)".
var releaseHeading = regexp.MustCompile(`(?m)^## (v\d+\.\d+\.\d+\S*)`)

// releaseVersion is the newest release in the root CHANGELOG.md (the first release heading; Unreleased comes before
// it). The release tool stamps that heading in the release commit, so the pill changes with it.
func releaseVersion(root string) (string, error) {
	b, err := os.ReadFile(filepath.Join(root, "CHANGELOG.md"))
	if err != nil {
		return "", err
	}
	m := releaseHeading.FindSubmatch(b)
	if m == nil {
		return "", fmt.Errorf("CHANGELOG.md: no release heading (## vX.Y.Z)")
	}
	return string(m[1]), nil
}

func versionFile(root string, out map[string]string) error {
	v, err := releaseVersion(root)
	if err != nil {
		return err
	}
	out[versionOut] = fmt.Sprintf("// Generated by site/sync: PocketOne's current release, the newest in CHANGELOG.md.\nmodule.exports = %q\n", v)
	return nil
}
