package main

// The Pages starter kits on pocketone.dev: a page per kit (/docs/starters/<kit>) made from its README
// (ext/pages/starters/<kit>/README.md), the table of kits on the Starter kits page, and the Starter kits nav
// (toc-starters, a link per kit), which the main nav's How-to guides slide into. A new kit folder shows up everywhere on
// the next sync.

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

const (
	startersDir   = "ext/pages/starters"
	startersOut   = "site/pb_pages/(main)/docs/starters"
	startersIndex = startersOut + "/index.md"
	startersURL   = "/docs/starters"
	startersNav   = "site/pb_pages/(main)/_private/toc-starters.md"
	startersStart = "<!-- starters:start (generated by site/sync from ext/pages/starters/*/README.md) -->"
	startersEnd   = "<!-- starters:end -->"
)

type starterKit struct {
	Name, Title, Summary, Body string
}

var starterTitleRe = regexp.MustCompile(`(?m)^#\s+(.+?)\s*$`)

// starterKits reads every kit's README, sorted by name.
func starterKits(root string) ([]starterKit, error) {
	entries, err := os.ReadDir(filepath.Join(root, startersDir))
	if err != nil {
		return nil, err
	}
	var out []starterKit
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		raw, err := os.ReadFile(filepath.Join(root, startersDir, e.Name(), "README.md"))
		if err != nil {
			return nil, fmt.Errorf("%s/%s: a starter kit needs a README.md: %w", startersDir, e.Name(), err)
		}
		s := string(raw)
		k := starterKit{Name: e.Name(), Title: e.Name(), Body: s}
		if m := starterTitleRe.FindStringSubmatchIndex(s); m != nil {
			k.Title = s[m[2]:m[3]]
			k.Body = strings.TrimSpace(s[m[1]:])
		}
		for _, para := range strings.Split(k.Body, "\n\n") {
			if p := strings.TrimSpace(para); p != "" && !strings.HasPrefix(p, "```") && !strings.HasPrefix(p, "#") {
				k.Summary = firstSentence(strings.Join(strings.Fields(p), " "))
				break
			}
		}
		out = append(out, k)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out, nil
}

// starterNavTitle is the kit's name in the nav: its README title without " starter".
func starterNavTitle(k starterKit) string {
	return strings.TrimSuffix(strings.TrimSuffix(k.Title, " starter"), " Starter")
}

// starterPages writes each kit's page and the Starter kits page's table.
func starterPages(root string, out map[string]string) error {
	kits, err := starterKits(root)
	if err != nil {
		return err
	}
	for _, k := range kits {
		var b strings.Builder
		b.WriteString(frontMatter(k.Title, k.Summary, startersDir+"/"+k.Name+"/README.md"))
		fmt.Fprintf(&b, "# %s\n\n", k.Title)
		fmt.Fprintf(&b, "Its files are in [`%s/%s`](%s/tree/main/%s/%s). See every [starter kit](%s).\n\n",
			startersDir, k.Name, repoURL, startersDir, k.Name, startersURL)
		b.WriteString(k.Body + "\n")
		out[startersOut+"/"+k.Name+".md"] = escapeEJS(b.String())
	}
	raw, err := os.ReadFile(filepath.Join(root, startersIndex))
	if err != nil {
		return nil
	}
	page := string(raw)
	i, j := strings.Index(page, startersStart), strings.Index(page, startersEnd)
	if i < 0 || j < i {
		return nil
	}
	var t strings.Builder
	t.WriteString(startersStart + "\n\n| Kit | What it is |\n|---|---|\n")
	for _, k := range kits {
		fmt.Fprintf(&t, "| [%s](%s/%s) | %s |\n", k.Name, startersURL, k.Name, cell(k.Summary))
	}
	t.WriteString("\n" + startersEnd)
	out[startersIndex] = page[:i] + t.String() + page[j+len(startersEnd):]

	var nav strings.Builder
	nav.WriteString("<!-- Generated by site/sync from ext/pages/starters. Edit those READMEs, then run site/sync. -->\n\n# Starter kits\n\n" +
		backLink + "- [All starter kits](" + startersURL + ")\n\n# Kits\n\n")
	for _, k := range kits {
		fmt.Fprintf(&nav, "- [%s](%s/%s)\n", starterNavTitle(k), startersURL, k.Name)
	}
	out[startersNav] = nav.String()
	return nil
}
